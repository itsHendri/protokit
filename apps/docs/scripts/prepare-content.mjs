#!/usr/bin/env node
/**
 * Pages generated from the kit itself, so the site cannot disagree with it. Runs before `next dev` and
 * `next build`; the outputs are gitignored.
 *   content/docs/patterns.mdx  ← apps/{mobile,web}/DESIGN_SYSTEM.md › Patterns + Anti-patterns
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const docs = join(dirname(fileURLToPath(import.meta.url)), '..');
const designSystem = {
  mobile: readFileSync(join(docs, '../mobile/DESIGN_SYSTEM.md'), 'utf8'),
  web: readFileSync(join(docs, '../web/DESIGN_SYSTEM.md'), 'utf8'),
};

/** The body of a `## Heading` section, up to the next `## `. */
function section(md, heading) {
  const start = md.indexOf(`\n## ${heading}\n`);
  if (start === -1) throw new Error(`DESIGN_SYSTEM.md has no "## ${heading}" section`);
  const rest = md.slice(start + heading.length + 5);
  const end = rest.indexOf('\n## ');
  return (end === -1 ? rest : rest.slice(0, end)).trim();
}

/** Escape what MDX would read as JSX or expressions, outside `code spans`. */
const mdxSafe = (md) =>
  md
    .split(/(`[^`]*`)/g)
    .map((part) => (part.startsWith('`') ? part : part.replace(/[{}<>]/g, (ch) => `\\${ch}`)))
    .join('');

const kitPart = (platform, label) => `## ${label}

### Patterns

${mdxSafe(section(designSystem[platform], 'Patterns'))}

### Anti-patterns

${mdxSafe(section(designSystem[platform], 'Anti-patterns'))}
`;

const page = `---
title: Patterns
description: How screens are put together in each kit, and what to avoid. Generated from the kits' DESIGN_SYSTEM.md.
---

{/* GENERATED by scripts/prepare-content.mjs from apps/mobile/DESIGN_SYSTEM.md and apps/web/DESIGN_SYSTEM.md — edit those files. */}

These are the same rules the agent reads, straight from each kit's \`DESIGN_SYSTEM.md\`.

${kitPart('mobile', 'Mobile')}
${kitPart('web', 'Web')}
## The hallucination guard

${mdxSafe(section(designSystem.mobile, 'Hallucination guard'))}
`;

writeFileSync(join(docs, 'content/docs/patterns.mdx'), page);
console.log('prepare-content → content/docs/patterns.mdx');
